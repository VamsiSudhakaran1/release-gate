#!/usr/bin/env python3
"""The semantic provider benchmark — which model to trust with a reading, and why.

The third harness beside `run.py` (the scanner) and `assurance.py` (the
assurance layer), and deliberately apart from both. It measures the providers
a semantic verifier can be configured with: fifteen labelled Release-Gate
questions, asked through the production verifier, scored so that false
certainty costs most (`release_gate/assurance/provider_benchmark.py`).

    python benchmark/semantic.py                    # the reference providers
    python benchmark/semantic.py --provider env --repeats 3 --out runs.jsonl
                                                    # + the provider RG_SEMANTIC_* configures
    python benchmark/semantic.py --from a.jsonl b.jsonl
                                                    # re-score saved runs; no model is called
    python benchmark/semantic.py --json             # machine output
    python benchmark/semantic.py --md               # regenerate benchmark/SEMANTIC.md

`--cases FILE` adds your own labelled cases (repeatable); `--policy FILE` scores
under another benchmark policy. The ranking is a measurement for a person to
read: nothing here configures a provider or decides anything about a release.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent))

from release_gate.assurance.provider_benchmark import (  # noqa: E402
    BENCHMARK_CATEGORIES, BENCHMARK_SCORING, DEFAULT_BENCHMARK_POLICY, BenchmarkError,
    BenchmarkPolicy, cases_digest, evaluate_benchmark, question_labels,
    read_benchmark_cases, read_benchmark_runs, reference_providers, render_benchmark,
    run_benchmark, write_benchmark_runs)

CASES = ROOT / "semantic_cases.jsonl"
#: The published results are the reference providers', run twice each so
#: repeatability shows, under a fixed clock and timer so the page is the same
#: on every run.
MD_REPEATS = 2


def reference_run(cases, policy=DEFAULT_BENCHMARK_POLICY):
    providers = reference_providers(question_labels(cases))
    return run_benchmark(cases, providers, policy=policy, repeats=MD_REPEATS,
                         clock=lambda: "", timer=lambda: 0.0)


def _pct(value) -> str:
    return "—" if value is None else f"{value:.0%}"


def _num(value) -> str:
    return "—" if value is None else f"{value:.2f}"


def render_md(report: Dict[str, Any], cases) -> str:
    policy = report["policy"]
    providers = report["providers"]
    o: List[str] = [
        "# release-gate semantic provider benchmark — reference results", "",
        "> Generated by `python benchmark/semantic.py --md`. The cases are "
        "`benchmark/semantic_cases.jsonl`; the harness is "
        "`release_gate/assurance/provider_benchmark.py`. Re-run it yourself, and "
        "run it against your own provider with `--provider env`.", "",
        f"**Cases:** {len(cases)} labelled questions across "
        f"{len({c.category for c in cases})} categories. **Scoring:** "
        f"`{BENCHMARK_SCORING}`. **Cases digest:** `{cases_digest(cases)}`.", "",
        "## What this measures, and what it does not", "",
        "It measures how a provider answers the questions a semantic verifier "
        "asks: whether a packet of evidence supports a claim, contradicts it, or "
        "leaves it unsettled. The rows below are **reference providers**, "
        "in-process and model-free, published so the scale can be read: what a "
        "ceiling, a confident confirmer, a constant abstainer, a word-matcher "
        "and an unstable answerer score.", "",
        "| This benchmark… | |", "|---|---|",
        "| measures a model's general ability | **False** — fifteen narrow, "
        "Release-Gate-shaped questions |",
        "| has independently adjudicated labels | **False** — each label was "
        "written with its case, with its rationale below; add reviewed cases with "
        "`--cases` |",
        "| ranks by raw accuracy | **False** — by mean score, among providers "
        "under the false-confirm ceiling |",
        "| chooses a provider | **False** — it is a measurement for a person |",
        "| affects any admission decision | **False** — a reading never decides "
        "(REFERENCE: semantic verifier) |", "",
        "## The score", "",
        "| Committed answer | Score |", "|---|---|",
        f"| the label (decisive, or `insufficient_evidence` when that is the label) "
        f"| **{policy['correct']:+.1f}** |",
        f"| `insufficient_evidence` on a decisive case | **{policy['abstained']:+.1f}** |",
        f"| nothing usable came back | **{policy['no_answer']:+.1f}** |",
        f"| `contradicted`, and it is not | **-{policy['false_refute']:.0f} × "
        "(1 + confidence)** |",
        f"| `supported`, and it is not | **-{policy['false_confirm']:.0f} × "
        "(1 + confidence)** |", "",
        "Abstaining when unsure always beats guessing wrong with confidence. A "
        "guess at `supported` pays only when it is right about nine times in "
        "ten. A provider is ranked only if its false-confirm rate is at most "
        f"{policy['max_false_confirm_rate']:.0%}, it answers at least "
        f"{policy['min_answer_rate']:.0%} of the time, and, when asked more than "
        f"once, it gives the same answer at least {policy['min_repeatability']:.0%} "
        "of the time.", "",
        "## Reference results", "",
        "| Provider | Ranked | Mean score | Accuracy | Decisive | False confirm "
        "| False refute | Abstention P / R | Brier | Repeatable | Context kept |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for position, name in enumerate(report["ranking"] + report["not_ranked"], 1):
        p = providers[name]
        ranked = str(position) if name in report["ranking"] else "no"
        o.append(f"| `{name}` | {ranked} | {_num(p['mean_score'])} | "
                 f"{_pct(p['accuracy'])} | {_pct(p['coverage'])} | "
                 f"{_pct(p['false_confirm_rate'])} | {_pct(p['false_refute_rate'])} | "
                 f"{_pct(p['abstention_precision'])} / {_pct(p['abstention_recall'])} | "
                 f"{_num(p['calibration']['brier'])} | "
                 f"{_pct(p['determinism']['repeatability'])} | "
                 f"{_pct(p['context']['accuracy_retained'])} |")
    o += ["", "Brier is over stated probabilities only; a chat provider's "
          "self-reported confidence is not a probability and is not scored as one. "
          "*Context kept* is accuracy on excerpts cut to "
          f"{policy['tiers'][-1][1]} characters, as a share of accuracy on "
          f"{policy['tiers'][0][1]}. Reference providers run in-process, so latency "
          "and cost are not shown; for a real provider the report gives latency "
          "p50/p95 and declared cost.", ""]
    if report["not_ranked"]:
        o += ["**Not ranked:**", ""]
        o += [f"- `{n}`: {'; '.join(providers[n]['ineligible_because'])}"
              for n in report["not_ranked"]]
        o.append("")
    o += ["## The cases", "",
          "| Case | Category | Label | Why |", "|---|---|---|---|"]
    for case in cases:
        o.append(f"| `{case.case_id}` | {case.category} — "
                 f"{BENCHMARK_CATEGORIES[case.category]} | `{case.label.value}` | "
                 f"{case.rationale} |")
    o += ["", "## Benchmark your provider", "", "```bash",
          "export RG_SEMANTIC_BASE_URL=http://localhost:11434/v1 RG_SEMANTIC_MODEL=llama3.1",
          "python benchmark/semantic.py --provider env --repeats 3 --out llama.jsonl",
          "python benchmark/semantic.py --from llama.jsonl other.jsonl   "
          "# compare saved runs",
          "```", ""]
    return "\n".join(o)


def _env_provider(label: str):
    from release_gate.semantic_providers import provider_from_env
    provider = provider_from_env()
    identity = provider.identity()
    return label or f"env:{identity.provider}:{identity.model}", provider


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(
        description="Benchmark semantic-verification providers; false certainty costs most.")
    parser.add_argument("--cases", action="append", default=[],
                        help="labelled case file(s) (default: benchmark/semantic_cases.jsonl)")
    parser.add_argument("--provider", action="append", default=[], metavar="env[=LABEL]",
                        help="add the provider RG_SEMANTIC_* configures")
    parser.add_argument("--no-references", action="store_true",
                        help="leave out the reference providers")
    parser.add_argument("--repeats", type=int, default=1,
                        help="ask the scored tier this many times (default 1)")
    parser.add_argument("--policy", help="a benchmark policy JSON file")
    parser.add_argument("--from", dest="runs", nargs="+", default=[],
                        help="re-score saved runs instead of asking anything")
    parser.add_argument("--out", help="write every reading as JSONL")
    parser.add_argument("--json", action="store_true", help="print the report as JSON")
    parser.add_argument("--md", action="store_true",
                        help="regenerate benchmark/SEMANTIC.md (reference providers only)")
    args = parser.parse_args(argv)
    try:
        policy = (BenchmarkPolicy.from_dict(json.loads(Path(args.policy).read_text()))
                  if args.policy else DEFAULT_BENCHMARK_POLICY)
        cases = read_benchmark_cases(*(args.cases or [CASES]))
        if args.md:
            report = evaluate_benchmark(reference_run(cases))
            (ROOT / "SEMANTIC.md").write_text(render_md(report, cases), encoding="utf-8")
            print(f"wrote {ROOT / 'SEMANTIC.md'}")
            return 0
        if args.runs:
            rows = read_benchmark_runs(*args.runs)
        else:
            providers: Dict[str, Any] = ({} if args.no_references else
                                         reference_providers(question_labels(cases)))
            for spec in args.provider:
                kind, _, label = spec.partition("=")
                if kind != "env":
                    raise BenchmarkError(f"--provider takes env[=LABEL], not {spec!r}")
                name, provider = _env_provider(label)
                providers[name] = provider
            if not providers:
                raise BenchmarkError("nothing to benchmark: add --provider env, or keep "
                                     "the reference providers")
            rows = run_benchmark(cases, providers, policy=policy, repeats=args.repeats)
        if args.out:
            write_benchmark_runs(rows, args.out)
        report = evaluate_benchmark(rows, policy=policy)
        if not args.runs:
            report["cases_digest"] = cases_digest(cases)
    except (BenchmarkError, OSError, ValueError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(report, indent=2, sort_keys=True) if args.json
          else render_benchmark(report))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
