#!/usr/bin/env python3
"""The assurance benchmark — sixteen constructed cases, scored by class.

The sibling of `benchmark/run.py`, and deliberately not merged with it. That one
measures the **scanner**: code in, rule ids out, over 93 snippets. This one
measures the **assurance layer**: a case in, a verdict plus findings plus
coverage plus invalidation behaviour out. Two layers, two corpora, two scope
statements — because a reader who finds one precision figure and assumes it
covers the other layer has been over-claimed at, and keeping them in one file is
how that happens.

    python benchmark/assurance.py          # human report
    python benchmark/assurance.py --json   # machine output
    python benchmark/assurance.py --md     # regenerate benchmark/ASSURANCE.md

Exit code is 1 if any case fails, so CI can run it as a gate.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from release_gate.assurance.corpus import (  # noqa: E402
    BEHAVIOURS, CaseClass, build_corpus, score,
)

ROOT = Path(__file__).resolve().parent


def _rate(value):
    return "—" if value is None else f"{value:.1%}"


def render_md(result) -> str:
    scope = result.scope
    corpus = {c.case_id: c for c in build_corpus()}
    o = [
        "# release-gate assurance benchmark — results", "",
        "> Generated by `python benchmark/assurance.py --md`. The corpus is "
        "`release_gate/assurance/corpus.py`; re-run it yourself.", "",
        f"**Corpus:** {scope.cases} constructed cases across {scope.kinds} kinds. "
        f"**{result.passed} of {len(result.results)} pass.**", "",
        "## What this measures, and what it does not", "",
        "Every case here is **constructed**, so its evidence structure is known "
        "by construction rather than by judgement. That is the ground truth: "
        "whether release-gate correctly reports the structure it was given.",
        "",
        "It is **not** a measurement of whether a release is safe. A case "
        "labelled `invalid_release` means *a case whose evidence structure "
        "carries a named defect that was put there*, never *a release that was "
        "actually bad*. Release-gate holds no truth about release safety and "
        "claiming one here would be the universal truth claim Invariant 10 "
        "refuses.", "",
        "| This benchmark… | |", "|---|---|",
        f"| measures release safety | **{scope.measures_release_safety}** |",
        f"| measures the static scanner | **{scope.measures_the_scanner}** "
        "— `benchmark/run.py` does, over a different corpus |",
        f"| generalises to unseen case shapes | **{scope.generalises_to_unseen_shapes}** "
        "— constructed cases prove the engine handles these constructions |",
        f"| is a third-party audit | **{scope.is_a_third_party_audit}** "
        "— same author as the engine, published so it can be re-run |",
        f"| establishes that a PROMOTE was correct | "
        f"**{scope.establishes_that_a_promote_was_correct}** — a PROMOTE is a "
        "recommendation to a person (Invariant 15) |", "",
        "## Precision, and where it lives", "",
        "One precision figure, at the **case** level: of the cases the gate "
        "stopped, how many had a defect built in?", "",
        f"| | |", "|---|---|",
        f"| Cases stopped that had a defect built in | **{result.flagged_with_defect}** |",
        f"| Cases stopped that were clean | **{result.flagged_without_defect}** |",
        f"| Precision | **{_rate(result.precision)}** |", "",
        "There is deliberately **no per-class precision**. A false positive is "
        "only ever counted against a clean case, so a detection-class precision "
        "would be 1.0 by construction — a number that can only come out perfect, "
        "which is worse than no number. And a structural defect legitimately "
        "produces a cascade: a failed verification really does create a "
        "contradiction and a replication disagreement, so counting the "
        "unexpected-but-correct siblings as false positives would be wrong in "
        "the other direction. Precision belongs where the clean cases can make "
        "it come out wrong.", "",
        "**Detection is not gating, and the two are separate columns.**",
        "",
        f"Detected and promoted anyway: "
        + (", ".join(f"`{c}`" for c in result.detected_but_not_gated)
           or "none") + ". These raise only advisory findings. That is a "
        "reportable property of the engine, not a corpus failure — but a table "
        "that showed detection alone would let a rule that fires read as a rule "
        "that stopped something.", "",
        "## Per class", "",
        "| Class | What it asks | Cases | Rules expected | Found | Missed | Stopped | Recall | Behaviours |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    asks = {
        CaseClass.DETECTION.value: "a named defect is present — did the right rule fire?",
        CaseClass.QUIET.value: "nothing is wrong — did it stay quiet?",
        CaseClass.BEHAVIOUR.value: "what did it *do*? (no positive class)",
    }
    for name, s in result.by_class.items():
        o.append(f"| {name} | {asks[name]} | {s.cases} | {s.tp + s.fn} | {s.tp} | "
                 f"{s.fn} | {s.flagged} | {_rate(s.recall)} | "
                 f"{s.behaviours_passed}/{s.behaviours_run} |")
    o += [
        "", "A `—` means the question does not apply to that class. It is not a "
        "100% that was rounded, and it is deliberately not rendered as one: a "
        "QUIET case has no defect to recall, and a BEHAVIOUR case has no "
        "positive class at all.", "",
        "**A false positive on a QUIET case is a *blocking or holding* finding, "
        "not any finding.** Advisories are excluded: \"nothing declared what this "
        "system is permitted to do\" is a true statement about a case with no "
        "manifest, and counting it against a clean case would make the corpus "
        "reward silence. Findings the active methodology *accepted* are excluded "
        "too — an acceptance is a decision taken in advance that a structural "
        "fact does not disqualify here, and the finding still stands and is still "
        "shown.", "",
        "## Per case", "",
        "| Case | Kind | Class | Verdict | Expected rules | Result |",
        "|---|---|---|---|---|---|",
    ]
    for r in result.results:
        expected = ", ".join(f"`{x}`" for x in corpus[r.case_id].expect_rules) or "—"
        if r.case_class is CaseClass.BEHAVIOUR:
            detail = f"{sum(1 for ok, _ in r.behaviours.values() if ok)}/" \
                     f"{len(r.behaviours)} checks"
        elif r.misses:
            detail = "MISSED " + ", ".join(r.misses)
        elif r.false_positives:
            detail = "FALSE POSITIVE " + ", ".join(r.false_positives)
        else:
            detail = "pass"
        o.append(f"| `{r.case_id}` | {r.kind} | {r.case_class.value} | {r.decision} | "
                 f"{expected} | {detail} |")

    o += ["", "## What each case builds in", "",
          "Written from the construction, before the engine was run against it. "
          "An expectation written after a run records what the engine does, which "
          "is a tautology wearing a test's clothes.", ""]
    for r in result.results:
        case = corpus[r.case_id]
        o.append(f"**`{r.case_id}`** — {case.defect}")
        if case.notes:
            o.append(f"  <br>*{case.notes}*")
        o.append("")

    o += ["## The behaviour checks", "",
          "Each answers a question precision cannot. They read what the engine "
          "returned, never the corpus's own expectations, so a check cannot pass "
          "by agreeing with the case that produced it.", "",
          "| Check | Question |", "|---|---|"]
    for name in sorted(BEHAVIOURS):
        o.append(f"| `{name}` | {BEHAVIOURS[name].question} |")

    o += ["", "## Known limitations, kept here on purpose", "",
          "- **No envelope-only case can carry an admissible verification.** "
          "`verification_method` on a submitted record is kept as a *declaration* "
          "and never credited, because a producer naming its own method is "
          "self-certification (§10r). So \"valid release\" here means structurally "
          "sound and self-consistent, never *verified*. Admissible verification "
          "reaches a case through a verifier adapter, which is a different input "
          "kind.",
          "- **Self-verification by identity alone is not separately flagged.** "
          "A claim naming its own producer as verifier raises no rule of its own — "
          "the engine never credits a declared attempt as verification in the "
          "first place, so there is nothing to withdraw. Reported here as a scope "
          "note rather than a detection.",
          "- **Detection and decision are separate columns.** `false_independence` "
          "is detected and ADVISORY: the case still promotes. Collapsing the two "
          "would let a rule that fires count as a rule that stopped something.",
          "- **Sixteen cases is sixteen cases.** Every rate above is over a "
          "denominator small enough to print, which is why the denominators are "
          "printed.", ""]

    if result.failures:
        o += ["## Failing cases (current)", ""]
        for f in result.failures:
            o.append(f"- `{f.case_id}`: "
                     + ("missed " + ", ".join(f.misses) if f.misses else "")
                     + ("false positive " + ", ".join(f.false_positives)
                        if f.false_positives else "")
                     + "; ".join(f"{n} — {d}" for n, (ok, d) in f.behaviours.items()
                                 if not ok))
        o.append("")
    return "\n".join(o)


def main() -> int:
    result = score()
    if "--json" in sys.argv:
        print(json.dumps(result.to_dict(), indent=2))
        return 0 if not result.failures else 1
    if "--md" in sys.argv:
        (ROOT / "ASSURANCE.md").write_text(render_md(result) + "\n", encoding="utf-8")
        print(f"wrote {ROOT / 'ASSURANCE.md'}")
        return 0 if not result.failures else 1
    print(f"cases={len(result.results)}  passed={result.passed}")
    print(f"case-level precision={_rate(result.precision)} "
          f"(stopped-with-defect {result.flagged_with_defect}, "
          f"stopped-clean {result.flagged_without_defect})")
    for name, s in result.by_class.items():
        print(f"  {name:<10} n={s.cases:<3} rules {s.tp}/{s.tp + s.fn}  "
              f"recall={_rate(s.recall)}  stopped={s.flagged}  "
              f"behaviours={s.behaviours_passed}/{s.behaviours_run}")
    if result.detected_but_not_gated:
        print("  detected and promoted anyway: "
              + ", ".join(result.detected_but_not_gated))
    for f in result.failures:
        print(f"  FAIL {f.case_id}: misses={list(f.misses)} "
              f"false_positives={list(f.false_positives)}")
        for n, (ok, detail) in f.behaviours.items():
            if not ok:
                print(f"       {n}: {detail}")
    print("scope: this measures whether the reported structure matches the built "
          "one. It does not measure release safety.")
    return 0 if not result.failures else 1


if __name__ == "__main__":
    sys.exit(main())
