class TestPromote:

    def test_promote_only_when_a_methodology_is_met_and_nothing_holds(self):
        outcome = assure(str(PROMOTED), methodology=GENERAL)
        assert outcome.decision.value == "PROMOTE"
        assert not conditions(outcome, E.HOLD) and not conditions(outcome, E.BLOCK)
        assert any(c.effect is E.SATISFIED for c in conditions(outcome))
        assert outcome.admission.basis.startswith("PROMOTE under general-agent-action")

    def test_the_same_case_without_a_methodology_holds(self):
        outcome = assure(str(PROMOTED))
        assert outcome.decision.value == "HOLD"
        held = [c.condition_id for c in conditions(outcome, E.HOLD)]
        assert "RG-ZC-001" in held

    def test_a_methodology_nothing_of_which_applies_is_no_basis(self, tmp_path):
        import dataclasses
        from release_gate.assurance.case import CaseType
        only_research = dataclasses.replace(
            GENERAL.requirements[0], applies_to_case_types=(CaseType.RESEARCH_RESULT,))
        narrow = AssuranceMethodology(
            methodology_id="narrow", version="1.0.0", domain="test",
            case_types=GENERAL.case_types, description="one requirement, for research",
            requirements=(only_research,))
        outcome = assure(str(PROMOTED), methodology=narrow)
        assert outcome.assessment.status.value == "ASSESSED"
        assert all(r.outcome.value == "NOT_APPLICABLE" for r in outcome.assessment.results)
        assert outcome.decision.value == "HOLD"
        assert any("there is no basis on which to promote" in r
                   for r in outcome.case.verdict.reasons)


class TestBlock:

    def test_a_critical_counterexample_blocks(self):
        outcome = assure(str(RELEASE))
        assert outcome.decision.value == "BLOCK"
        assert {c.dimension for c in outcome.admission.blocking} >= {D.COUNTEREXAMPLES}

    def test_a_refuted_mandatory_claim_blocks(self, tmp_path):
        rows = [{"record_type": "claim", "claim_id": "c", "is_root": True,
                 "proposition": "the migration is reversible", "producer": P("t", "human")},
                {"record_type": "evidence", "evidence_id": "e", "kind": "TEST_RESULT",
                 "producer": P("ci"), "contradicts_claims": ["c"], "coverage_note": "x",
                 "summary": "rollback lost 14 rows"}]
        outcome = run(tmp_path, rows, methodology=GENERAL)
        assert outcome.decision.value == "BLOCK"
        assert any(c.dimension is D.CONTRADICTIONS and c.claims == ("c",)
                   for c in outcome.admission.blocking)

    def test_a_policy_threshold_stated_as_blocking_blocks(self, tmp_path):
        from release_gate.assurance.methodology import MinimumRecords
        strict = GENERAL.extend(
            methodology_id="strict", version="1.0.0",
            add_requirements=[Requirement(
                requirement_id="evidence.three", description="at least three records",
                predicate=MinimumRecords(collection="evidence", minimum=50),
                effect=RequirementEffect.BLOCK)])
        outcome = assure(str(PROMOTED), methodology=strict)
        assert outcome.decision.value == "BLOCK"
        [block] = outcome.admission.blocking
        assert block.condition_id == "evidence.three"
        assert block.dimension is D.REQUIRED_EVIDENCE and block.source == \
            "methodology requirement"

    def test_no_score_overrides_a_critical_failure(self, tmp_path):
        rows = promoted_rows() + [
            {"record_type": "evidence", "evidence_id": "e-score", "kind": "OTHER",
             "producer": P("scanner"), "supports_claims": ["C-1"], "coverage_note": "x",
             "score": 100, "decision": "PROMOTE", "assurance_level": "FRONTIER",
             "confidence": 1.0},
            {"record_type": "counterexample", "target_claim": "C-1", "result": "FOUND",
             "producer_id": "red-team", "method": "SIMULATION",
             "detail": "EUR 0.005 rounds the wrong way"}]
        outcome = run(tmp_path, rows, methodology=GENERAL)
        assert outcome.decision.value == "BLOCK"
        assert outcome.to_dict()["admission"]["decided_by_score"] is False


class TestHold:

    def test_hold_is_a_first_class_outcome(self, tmp_path):
        rows = [{"record_type": "claim", "claim_id": "c", "is_root": True,
                 "proposition": "the change is safe", "producer": P("t", "human")}]
        outcome = run(tmp_path, rows, methodology=GENERAL)
        assert outcome.decision.value == "HOLD" and outcome.exit_code == 10
        held = conditions(outcome, E.HOLD)
        assert held and all(c.summary for c in held)
        assert outcome.admission.basis.startswith("HOLD under general-agent-action")

    def test_insufficient_independence_holds_when_the_policy_says(self, tmp_path):
        codex = {"agent": "codex", "session": "s-A"}
        rows = promoted_rows()
        rows[-1] = dict(rows[-1], supporting_evidence=[], verification_attempts=[
            {"method": "TEST_SUITE", "outcome": "PASSED", "verifier": "ci",
             "provenance": codex},
            {"method": "HUMAN_REVIEW", "outcome": "PASSED", "verifier": "review",
             "provenance": codex}])
        rows.append({"record_type": "authorship", "role": "implementation",
                     "provenance": codex})
        policy = ResolutionPolicy(policy_id="independent",
                                  author_independence=AdmissionEffect.HOLD)
        outcome = run(tmp_path, rows, methodology=GENERAL, resolution_policy=policy)
        assert outcome.decision.value == "HOLD"
        assert any(c.condition_id == "RG-INDEP-007" and c.dimension is D.INDEPENDENCE
                   for c in conditions(outcome, E.HOLD))


