def promoted_rows():
    return [json.loads(line) for line in PROMOTED.read_text().splitlines() if line.strip()]


def run(tmp_path, rows, name="case.json", **kw):
    path = tmp_path / name
    path.write_text(json.dumps(rows), encoding="utf-8")
    return assure(str(path), **kw)


def conditions(outcome, effect=None):
    return [c for c in outcome.admission.conditions if effect is None or c.effect is effect]


def P(pid, kind="agent"):
    return {"producer_id": pid, "kind": kind}


# ── the decision is the conditions ──────────────────────────────────────────

class TestTheDecisionIsTheConditions:

    def test_every_analyser_rule_has_an_admission_dimension(self):
        source = (ROOT / "release_gate/assurance/analysis.py").read_text()
        rules = set(re.findall(r'rule_id="(RG-[A-Z]+-\d+)"', source))
        assert rules
        unplaced = sorted(r for r in rules if dimension_of_rule(r) is D.OTHER)
        assert not unplaced, unplaced

    def test_the_thirteen_dimensions_the_admission_asks_about_exist(self):
        names = {d.value for d in AdmissionDimension}
        assert {"critical_claims", "claim_status", "coverage", "counterexamples",
                "contradictions", "assumptions", "state_binding", "independence",
                "required_evidence", "approvals", "exceptions", "unknowns",
                "failed_branches"} <= names

    @pytest.mark.parametrize("path,methodology", [
        (RELEASE, None), (PROMOTED, GENERAL), (PROMOTED, None),
        (ROOT / "examples/agents/04-production-db-change.jsonl", GENERAL),
        (ROOT / "examples/assurance/research-claim.jsonl",
         default_registry().resolve("research-assurance@1.0.0"))])
    def test_the_recorded_verdict_is_the_evaluation(self, path, methodology):
        outcome = assure(str(path), methodology=methodology)
        verdict, evaluation = outcome.case.verdict, outcome.admission
        assert verdict.decision is evaluation.decision
        assert verdict.fired_rules == evaluation.fired_rules
        assert verdict.reasons == evaluation.reasons
        worst = min((c.effect for c in evaluation.conditions),
                    key=lambda e: list(E).index(e))
        if evaluation.decision.value == "BLOCK":
            assert worst is E.BLOCK
        elif evaluation.decision.value == "PROMOTE":
            assert worst not in (E.BLOCK, E.HOLD)
        else:
            assert worst is E.HOLD

    def test_it_is_a_function_of_the_case(self):
        a = assure(str(RELEASE)).admission.to_dict()
        b = assure(str(RELEASE)).admission.to_dict()
        assert a == b and a["decided_by_score"] is False

    def test_a_blocking_condition_names_the_claim_it_breaks(self):
        outcome = assure(str(RELEASE))
        cex = next(c for c in outcome.admission.blocking if c.condition_id == "RG-CEX-001")
        assert cex.dimension is D.COUNTEREXAMPLES
        assert cex.claims == ("cl_no_unauthorised_transfer",)
        assert "RG-CEX-001 (counterexamples, on cl_no_unauthorised_transfer)" in \
            outcome.admission.basis


