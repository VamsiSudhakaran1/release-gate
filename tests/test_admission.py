class TestSemanticUncertainty:

    @pytest.fixture
    def low_confidence(self, tmp_path):
        from test_semantic_verifier import answer, packet_for, rows, verify, write
        from release_gate.assurance.semantic_verifier import (
            DEFAULT_SEMANTIC_VERIFIER_POLICY)
        path = write(tmp_path, rows())
        packet = packet_for(assure(path))
        assertion, _ = verify(packet, answer(packet, confidence=0.2),
                              policy=DEFAULT_SEMANTIC_VERIFIER_POLICY)
        return path, assertion

    def test_low_confidence_never_blocks_by_default(self, low_confidence):
        path, assertion = low_confidence
        plain = assure(path)
        read = assure(path, semantic_assertions=[assertion])
        sem = next(f for f in read.analysis.findings if f.rule_id == "RG-SEM-002")
        assert sem.effect.value == "ADVISORY"
        assert read.decision is plain.decision
        assert read.decision.value != "BLOCK"

    def test_it_blocks_only_where_the_policy_says_uncertainty_blocks(self, low_confidence):
        path, assertion = low_confidence
        policy = ResolutionPolicy(policy_id="uncertainty-blocks",
                                  semantic_uncertainty=AdmissionEffect.BLOCK)
        read = assure(path, semantic_assertions=[assertion], resolution_policy=policy)
        sem = next(f for f in read.analysis.findings if f.rule_id == "RG-SEM-002")
        assert sem.effect.value == "BLOCK" and read.decision.value == "BLOCK"
        assert any(c.condition_id == "RG-SEM-002" and c.dimension is D.UNKNOWNS
                   for c in read.admission.blocking)

    def test_the_policy_field_round_trips_and_refuses_nonsense(self):
        policy = ResolutionPolicy(semantic_uncertainty=AdmissionEffect.HOLD)
        assert ResolutionPolicy.from_dict(policy.to_dict()) == policy
        assert ResolutionPolicy().to_dict()["semantic_uncertainty"] is None
        with pytest.raises(ResolutionError):
            ResolutionPolicy.from_dict({"semantic_uncertainty": "MAYBE"})


# ── approvals ───────────────────────────────────────────────────────────────

COMMIT = "abc1234"


def approval(decision="approve", role="payments-owner", commit=COMMIT, **more):
    row = {"record_type": "evidence", "kind": "APPROVAL",
           "producer": P("human://dana", "human"),
           "reviewer": {"id": "dana", "role": role}, "decision": decision,
           "coverage_note": "release approval", **more}
    if commit is not None:
        row["state"] = {"commit": commit}
    return row


def with_approvals(*rows, candidate=True):
    """The promoted release, every record bound to one commit, plus the approvals."""
    base = []
    for row in promoted_rows():
        if row.get("record_type") == "evidence":
            row = dict(row, state={"commit": COMMIT})
        elif row.get("record_type") == "claim":
            row = dict(row, verification_attempts=[
                dict(a, state={"commit": COMMIT}) for a in row["verification_attempts"]])
        base.append(row)
    if candidate:
        base.insert(0, {"record_type": "candidate", "components": {"commit": COMMIT}})
    return base + list(rows)


REQUIRING = OrganisationConfig(organisation_id="acme",
                               required_approvals=("payments-owner",)).apply_to(GENERAL)


def approvals(outcome):
    return {c.condition_id: c.effect for c in outcome.admission.in_dimension(D.APPROVALS)}


class TestApprovals:

    def test_an_approval_of_this_release_satisfies_it(self, tmp_path):
        outcome = run(tmp_path, with_approvals(approval()), methodology=REQUIRING)
        assert approvals(outcome) == {"org.approvals": E.SATISFIED,
                                      "org.approvals.refused": E.SATISFIED}
        assert outcome.decision.value == "PROMOTE"

    def test_no_approval_holds(self, tmp_path):
        outcome = run(tmp_path, with_approvals(), methodology=REQUIRING)
        assert approvals(outcome)["org.approvals"] is E.HOLD
        assert outcome.decision.value == "HOLD"

    def test_an_approval_of_another_commit_does_not_count(self, tmp_path):
        outcome = run(tmp_path, with_approvals(approval(commit="0000fff")),
                      methodology=REQUIRING)
        assert approvals(outcome)["org.approvals"] is E.HOLD
        result = next(r for r in outcome.assessment.results
                      if r.requirement_id == "org.approvals")
        assert "STALE" in result.detail

    def test_an_approval_that_names_no_state_does_not_count(self, tmp_path):
        outcome = run(tmp_path, with_approvals(approval(commit=None)),
                      methodology=REQUIRING)
        assert approvals(outcome)["org.approvals"] is E.HOLD

    def test_a_lapsed_approval_does_not_count(self, tmp_path):
        row = approval(expires_at="2026-01-01T00:00:00Z", evaluated_at="2026-10-01T00:00:00Z")
        outcome = run(tmp_path, with_approvals(row), methodology=REQUIRING)
        assert approvals(outcome)["org.approvals"] is E.HOLD

    def test_an_approval_by_another_role_does_not_count(self, tmp_path):
        outcome = run(tmp_path, with_approvals(approval(role="intern")),
                      methodology=REQUIRING)
        assert approvals(outcome)["org.approvals"] is E.HOLD

    def test_a_refusal_of_this_release_blocks(self, tmp_path):
        outcome = run(tmp_path, with_approvals(approval("changes_requested")),
                      methodology=REQUIRING)
        assert approvals(outcome)["org.approvals.refused"] is E.BLOCK
        assert outcome.decision.value == "BLOCK"

    def test_a_refusal_of_another_release_holds_and_does_not_block(self, tmp_path):
        outcome = run(tmp_path, with_approvals(approval("reject", commit="0000fff")),
                      methodology=REQUIRING)
        assert approvals(outcome) == {"org.approvals": E.HOLD,
                                      "org.approvals.refused": E.SATISFIED}
        assert outcome.decision.value == "HOLD"

    def test_an_approval_naming_what_no_stated_candidate_holds_does_not_count(
            self, tmp_path):
        """With no candidate stated, the case's own artifacts stand in, and an
        approval of a commit they do not name binds to nothing."""
        outcome = run(tmp_path, with_approvals(approval(), candidate=False),
                      methodology=REQUIRING)
        assert approvals(outcome)["org.approvals"] is E.HOLD
        assert outcome.decision.value != "PROMOTE"

    def test_with_no_candidate_at_all_it_is_not_assessed(self, monkeypatch):
        import release_gate.assurance.candidate as candidate
        outcome = assure(str(PROMOTED))
        monkeypatch.setattr(candidate, "candidate_for_case", lambda case: (None, []))
        finding = ApprovalRequired(roles=("payments-owner",)).evaluate(outcome.case)
        assert finding.outcome.value == "NOT_ASSESSED"

    def test_a_review_contract_approval_counts(self, tmp_path):
        review = {"schema": "release-gate.review/1", "reviews": [
            {"id": "rev-1", "reviewer": {"id": "dana", "role": "payments-owner"},
             "decision": "approve", "scope": "the release", "state": {"commit": COMMIT}}]}
        rows = with_approvals() + [{"record_type": "producer_export", "source": "r.json",
                                    "document": review}]
        outcome = run(tmp_path, rows, methodology=REQUIRING)
        assert approvals(outcome)["org.approvals"] is E.SATISFIED

    def test_the_predicates_are_declared_like_any_other(self):
        assert predicate_from_dict({"kind": "approval_required", "roles": ["owner"]}) == \
            ApprovalRequired(roles=("owner",))
        assert predicate_from_dict({"kind": "approval_not_refused"}) == ApprovalNotRefused()
        with pytest.raises(MethodologyError):
            ApprovalRequired(roles=())

    def test_the_configuration_key_is_read_and_written_only_when_set(self):
        config = OrganisationConfig.from_dict({"organisation_id": "acme",
                                               "required_approvals": ["owner"]})
        assert config.required_approvals == ("owner",)
        assert "required_approvals" not in OrganisationConfig(
            organisation_id="acme").to_dict()
        with pytest.raises(OrganisationConfigError):
            OrganisationConfig.from_dict({"required_approval": ["owner"]})


