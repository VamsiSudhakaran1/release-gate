"""The admission decision and the Admission Report.

Pinned here, against release_gate/assurance/admission.py and admission_report.py:

* the decision is taken over the case — claims, findings, requirements, open
  disagreements, exceptions — as conditions, each with its dimension, the
  claims it concerns and the policy that declared it; the worst one decides,
  and the verdict a case records is exactly the one it always recorded;
* PROMOTE only when a methodology was supplied and met and nothing holds or
  blocks; HOLD is a first-class outcome with reasons and remedies; BLOCK only
  when a declared blocking condition is established — a counterexample to a
  critical claim, a refuted mandatory claim, a methodology threshold stated as
  blocking, a required approval refused for this exact release;
* no score, level or count is an input, and none overrides a critical failure;
* a model's low confidence never blocks unless the policy says it does;
* the Admission Report reads that decision and computes nothing: candidate,
  state hash, policy and decision first, then critical claims by status, what
  stands in the way, and evidence sources split into generated by Release-Gate
  and imported.
"""

